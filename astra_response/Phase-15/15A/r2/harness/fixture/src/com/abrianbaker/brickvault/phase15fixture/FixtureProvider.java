package com.abrianbaker.brickvault.phase15fixture;

import android.content.ContentProvider;
import android.content.ContentValues;
import android.content.Context;
import android.content.pm.PackageManager;
import android.database.Cursor;
import android.database.MatrixCursor;
import android.net.Uri;
import android.os.Binder;
import android.os.ParcelFileDescriptor;
import android.provider.OpenableColumns;
import android.util.Log;
import java.io.File;
import java.io.FileNotFoundException;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;

/** Private generated bytes. Android enforces each temporary URI read grant. */
public final class FixtureProvider extends ContentProvider {
    private static final int READ = android.content.Intent.FLAG_GRANT_READ_URI_PERMISSION;
    private File directory;

    @Override public boolean onCreate() {
        directory = new File(getContext().getFilesDir(), "generated-fixtures-v1");
        if (!directory.isDirectory() && !directory.mkdirs()) return false;
        try {
            for (String name : new String[]{"A.png", "B.png", "C.png", "corrupt.png", "unsupported.gif"}) {
                try (InputStream source = getContext().getAssets().open(name); FileOutputStream output = new FileOutputStream(new File(directory, name), false)) {
                    byte[] buffer = new byte[8192];
                    int count;
                    while ((count = source.read(buffer)) != -1) output.write(buffer, 0, count);
                }
            }
            return true;
        } catch (IOException exception) { Log.e(FixtureCases.TAG, "event=fixture_prepare_failed"); return false; }
    }

    @Override public String getType(Uri uri) {
        FixtureCases.resolve(getContext(), uri);
        return uri.getLastPathSegment().equals("unsupported.gif") ? "image/gif" : "image/png";
    }

    private File file(Uri uri) throws FileNotFoundException {
        String leaf = uri.getLastPathSegment();
        if ("A-copy.png".equals(leaf)) leaf = "A.png";
        if ("revokedB.png".equals(leaf)) leaf = "B.png";
        File file = new File(directory, leaf);
        if ("oversize.png".equals(leaf) && (!file.isFile() || file.length() != 25L * 1024L * 1024L + 1L)) {
            try (InputStream prefix = getContext().getAssets().open("A.png"); FileOutputStream output = new FileOutputStream(file, false)) {
                byte[] buffer = new byte[65536];
                long written = 0;
                int count;
                while ((count = prefix.read(buffer)) != -1) { output.write(buffer, 0, count); written += count; }
                java.util.Arrays.fill(buffer, (byte) 0);
                long remaining = 25L * 1024L * 1024L + 1L - written;
                while (remaining > 0) { int amount = (int) Math.min(remaining, buffer.length); output.write(buffer, 0, amount); remaining -= amount; }
            } catch (IOException exception) { throw new FileNotFoundException("Generated oversize fixture unavailable"); }
        }
        return file;
    }

    @Override public ParcelFileDescriptor openFile(Uri uri, String mode) throws FileNotFoundException {
        if (!"r".equals(mode)) throw new FileNotFoundException("Fixture provider is read-only");
        String value = FixtureCases.resolve(getContext(), uri);
        int targetUid;
        try { targetUid = getContext().getPackageManager().getApplicationInfo(FixtureCases.TARGET, 0).uid; }
        catch (PackageManager.NameNotFoundException exception) { throw new FileNotFoundException("Exact target unavailable"); }
        int callerUid = Binder.getCallingUid();
        if (callerUid != targetUid && callerUid != getContext().getApplicationInfo().uid) throw new SecurityException("Fixture target refused");
        String run = uri.getPathSegments().get(1);
        String leaf = uri.getLastPathSegment();
        Log.i(FixtureCases.TAG, "event=open_file case=" + value + " run=" + run + " leaf=" + leaf + " callerUid=" + callerUid);
        if ("revoked".equals(value) && "A.png".equals(leaf)) revokeB(run, targetUid, Binder.getCallingPid());
        return ParcelFileDescriptor.open(file(uri), ParcelFileDescriptor.MODE_READ_ONLY);
    }

    private void revokeB(String run, int targetUid, int targetPid) throws FileNotFoundException {
        Context context = getContext();
        Uri revoked = FixtureCases.uri(run, "revokedB.png");
        boolean completed = context.getSharedPreferences(FixtureCases.PREFS, Context.MODE_PRIVATE).getBoolean("revoked_" + run, false);
        int before = context.checkUriPermission(revoked, targetPid, targetUid, READ);
        if (completed) {
            if (before != PackageManager.PERMISSION_DENIED) throw new FileNotFoundException("Revocation state unexpectedly changed");
            Log.i(FixtureCases.TAG, "event=revoke_previously_confirmed run=" + run + " targetUid=" + targetUid + " current=DENIED");
            return;
        }
        if (before != PackageManager.PERMISSION_GRANTED) {
            Log.e(FixtureCases.TAG, "event=revoke_precondition_failed run=" + run + " targetUid=" + targetUid + " before=DENIED");
            throw new FileNotFoundException("Required genuine read grant was absent");
        }
        long identity = Binder.clearCallingIdentity();
        int after;
        try {
            // The all-grants overload revokes the intent-owned grant, only at this
            // unique generated B URI. It never changes a package permission setting.
            context.revokeUriPermission(revoked, READ);
            after = context.checkUriPermission(revoked, targetPid, targetUid, READ);
            if (after != PackageManager.PERMISSION_DENIED) {
                Log.e(FixtureCases.TAG, "event=revoke_assertion_failed run=" + run + " targetUid=" + targetUid + " before=GRANTED after=GRANTED");
                throw new FileNotFoundException("OS did not revoke the generated read grant");
            }
            if (!context.getSharedPreferences(FixtureCases.PREFS, Context.MODE_PRIVATE).edit().putBoolean("revoked_" + run, true).commit())
                throw new FileNotFoundException("Fixture revocation evidence could not be recorded");
            Log.i(FixtureCases.TAG, "event=uri_read_revoked run=" + run + " leaf=revokedB.png targetUid=" + targetUid + " before=GRANTED after=DENIED method=all-grants-URI-overload");
        } finally { Binder.restoreCallingIdentity(identity); }
    }

    @Override public Cursor query(Uri uri, String[] projection, String selection, String[] args, String order) {
        FixtureCases.resolve(getContext(), uri);
        String[] columns = projection == null ? new String[]{OpenableColumns.DISPLAY_NAME, OpenableColumns.SIZE} : projection;
        MatrixCursor cursor = new MatrixCursor(columns);
        Object[] row = new Object[columns.length];
        for (int i = 0; i < columns.length; i++) {
            if (OpenableColumns.DISPLAY_NAME.equals(columns[i])) row[i] = uri.getLastPathSegment();
            if (OpenableColumns.SIZE.equals(columns[i])) try { row[i] = file(uri).length(); } catch (FileNotFoundException ignored) { row[i] = null; }
        }
        cursor.addRow(row);
        return cursor;
    }
    @Override public Uri insert(Uri uri, ContentValues values) { throw new UnsupportedOperationException("Fixture provider is read-only"); }
    @Override public int delete(Uri uri, String where, String[] args) { throw new UnsupportedOperationException("Fixture provider is read-only"); }
    @Override public int update(Uri uri, ContentValues values, String where, String[] args) { throw new UnsupportedOperationException("Fixture provider is read-only"); }
}
